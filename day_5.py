# 3.Logical Operator :-

# Type of Logical Operators

# and 
# or 
# not
# _______________________________________

# AND Operator
# If both cases are TRUE it gives TRUE , otherwise it gives FALSE.

# Examples:

a = True
b = False 
c = True 
print( a and b ) # False 
print(a and c ) # True 
print(b and c) # False 
# _______________________________________
# OR Operator

# If both case are FALSE it gives FALSE , otherwise it gives TRUE

# Examples 
a = True
b = False 
c = True 
print( a or b ) # True
print(a or c ) #True
print(b or c) # True 
# _______________________________________

# Not Operator

# It gives us reverse value.
 
# Example:-1
a = True 
print(not a ) # False 

# Example:-2
a = 10 
b = 20 
print(a == b) # False 
